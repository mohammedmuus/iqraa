extension Translate on BuildContext {
  String t(String key, [Map<String, Object> values = const {}]) => Strings.of(AppScope.of(this).prefs.language, key, values);

  /// Text for an error: the app's own wording for connection problems, the server's message otherwise.
  String describe(Object? error) {
    if (error is ApiException) {
      return Strings.has(error.code) ? t(error.code, {'address': error.address}) : error.message;
    }
    return t('generic');
  }
}
