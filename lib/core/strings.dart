  static bool has(String key) => _en.containsKey(key);

  static String of(String language, String key, [Map<String, Object> values = const {}]) {
    final table = switch (language) {
      'sw' => _sw,
      'ar' => _ar,
      _ => _en,
    };
    var text = table[key] ?? _en[key] ?? key;
    values.forEach((name, value) => text = text.replaceAll('{$name}', '$value'));
    return text;
  }
